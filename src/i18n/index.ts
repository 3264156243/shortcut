export function t(key: string, params?: Record<string, string>, locale: Locale = DEFAULT_LOCALE): string {
  let text = translations[locale]?.[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }
  return text;
}
