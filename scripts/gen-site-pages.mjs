#!/usr/bin/env node
// Generate both languages from shared templates and explicit bilingual content.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { features, pageCopy } from './site-content.mjs';
import { shell, home, featurePage, t } from './site-templates.mjs';
import * as utility from './site-utility-pages.mjs';
import { EN_UI } from './site-en.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../website');
const extras={download:['download'],changelog:['changelog-data','changelog'],faq:['faq'],feedback:['feedback']};
export function buildSite(languages=[false,true]) {
  for(const en of languages) {
    const pages=[{path:'index.html',page:'home',body:home(en),title:t(['ShortCut — 少绕一步，顺手每一步','ShortCut — Less friction. More flow.'],en),desc:t(['快捷启动、纸条任务墙、SC球与手机联动。让 Windows 桌面上的每一步，都更顺手。','Quick Launch, Task Wall, SC Ball and phone connectivity. A little less friction for your Windows desktop.'],en)},...features.map(f=>({path:'features/'+f.id+'.html',page:'features/'+f.id,title:t(f.name,en)+' | ShortCut',desc:t(f.intro,en),body:featurePage(f,en)})),...Object.keys(pageCopy).map(id=>({path:id+'.html',page:id,title:t(pageCopy[id].name,en)+' | ShortCut',desc:t(pageCopy[id].intro,en),body:utility[id](en),scripts:extras[id]}))];
    for(const p of pages){const file=resolve(root,en?'en':'',p.path);mkdirSync(dirname(file),{recursive:true});writeFileSync(file,shell(p.body,{...p,en}));}
    console.log((en?'English':'中文')+': '+pages.length+' pages generated');
  }
  writeFileSync(resolve(root,'assets/js/data-en.js'),'// Generated by scripts/gen-site-pages.mjs\nwindow.SC_EN = '+JSON.stringify(EN_UI,null,2)+';\n');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))buildSite();
